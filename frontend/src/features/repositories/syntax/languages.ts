const filenames: Readonly<Record<string, Language>> = {
  dockerfile: 'dockerfile',
  containerfile: 'dockerfile',
  makefile: 'makefile',
  gnumakefile: 'makefile',
  '.editorconfig': 'ini',
  '.gitconfig': 'ini',
  '.npmrc': 'ini',
  '.env': 'ini',
  '.bashrc': 'bash',
  '.zshrc': 'bash',
  '.profile': 'bash',
  '.htaccess': 'apache',
  gemfile: 'ruby',
  rakefile: 'ruby',
}

export function detectLanguage(path: string): Language | null {
  const name = path.split('/').at(-1)?.toLowerCase() ?? ''
  if (Object.hasOwn(filenames, name)) return filenames[name] ?? null
  if (/^(?:dockerfile|containerfile)\./.test(name)) return 'dockerfile'
  if (name.startsWith('.env.')) return 'ini'
  const extension = name.includes('.') ? (name.split('.').at(-1) ?? '') : ''
  return Object.hasOwn(extensions, extension) ? (extensions[extension] ?? null) : null
}
