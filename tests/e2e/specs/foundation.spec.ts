import { expect, test } from '@playwright/test'

test('Vite proxies public health and safe API errors to Slim', async ({ request }) => {
  const health = await request.get('/api/health')
  expect(health.status()).toBe(200)
  expect(await health.json()).toEqual({ status: 'ok' })
  for (const path of ['/api', '/api/does-not-exist']) {
    const missing = await request.get(path)
    expect(missing.status()).toBe(404)
    expect(missing.headers()['content-type']).toContain('application/json')
  }
  const privateResponse = await request.get('/api/workspace/preview-cache')
  expect(privateResponse.status()).toBe(401)
  expect(privateResponse.headers()['cache-control']).toBe('private, no-store')
})

test('direct navigation renders accessible workspace and admin sign-in screens', async ({ page }, testInfo) => {
  // /admin is the admin panel with its own sign-in; the workspace keeps /login.
  await page.goto('/admin/diagnostics')
  await expect(page.getByText('Sign in to the Glimpse admin panel.')).toBeVisible()
  await expect(page).toHaveURL(/\/admin\/login\?returnTo=%2Fadmin%2Fdiagnostics$/)
  await page.goto('/app/connections')
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  await expect(page).toHaveURL(/\/login\?returnTo=%2Fapp%2Fconnections$/)
  await expect(page.getByLabel('Username')).toHaveAttribute('autocomplete', 'username')
  // The tab shows the Glimpse icon and names the page.
  await expect(page).toHaveTitle('Sign in · Glimpse')
  const icon = await page.locator('link[rel="icon"]').getAttribute('href')
  expect(icon).toBe('/favicon.svg')
  const iconResponse = await page.request.get(icon!)
  expect(iconResponse.status()).toBe(200)
  expect(iconResponse.headers()['content-type']).toContain('image/svg+xml')
  await page.getByLabel('Password', { exact: true }).fill('test-only')
  await page.getByRole('button', { name: 'Show password' }).click()
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Hide password' }).click()
  await page.getByLabel('Password', { exact: true }).clear()
  await page.screenshot({ path: testInfo.outputPath('login-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('login-mobile.png'), fullPage: true })
})

test('cross-origin writes and anonymous probes are rejected', async ({ request }) => {
  const response = await request.post('/api/auth/login', { data: { password: 'test-only' }, headers: { Origin: 'https://attacker.example' } })
  expect(response.status()).toBe(403)
  const probe = await request.post('/api/workspace/connections/github/probe', { data: {}, headers: { Origin: 'http://127.0.0.1:5173' } })
  expect(probe.status()).toBe(401)
})

test('workspace user signs in, opens connections and signs out against real SQL', async ({ page, context }, testInfo) => {
  test.skip(!process.env.GLIMPSE_TEST_DB_DSN, 'A dedicated MySQL/MariaDB database is required.')
  await page.goto('/app/connections#github-connection')
  await expect(page).toHaveURL(/\/login\?returnTo=/)
  await page.getByLabel('Username').fill('E2E.Owner')
  await page.getByLabel('Password', { exact: true }).fill('local-e2e-password-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  // After sign-in the browser returns to the requested workspace page and its GitHub card.
  await expect(page).toHaveURL(/\/app\/connections#github-connection$/)
  await expect(page.locator('#github-connection')).toBeFocused()
  const mask = (token: string) => token.slice(0, Math.floor(token.length / 2)) + '*'.repeat(Math.ceil(token.length / 2))
  await expect(page.getByText(mask('fixture_token_for_e2e.owner'), { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Configure GitHub' }).click()
  const dialog = page.getByRole('dialog', { name: 'Configure GitHub' })
  await expect(dialog.getByLabel('Personal access token')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: 'Configure GitHub' })).toBeFocused()
  await page.getByRole('button', { name: 'Configure GitHub' }).click()
  await dialog.getByLabel('Personal access token').fill('fixture_token_replacement')
  await page.screenshot({ path: testInfo.outputPath('configure-github-desktop.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Save & verify' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText(mask('fixture_token_replacement'), { exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('GitHub connected as fixture-user.')
  expect(await page.content()).not.toContain('fixture_token_replacement')
  await page.getByRole('link', { name: 'Open repositories' }).click()
  await expect(page.getByRole('heading', { name: 'Repositories', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: /fixture\/alpha/ })).toBeVisible()
  const cookie = (await context.cookies()).find(cookie => cookie.name === 'glimpse_workspace')
  expect(cookie?.httpOnly).toBe(true)
  expect(cookie?.sameSite).toBe('Lax')
  expect(cookie?.path).toBe('/api')
  await expect(page.getByText('e2e.owner', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('admin-desktop.png'), fullPage: true })
  await page.getByRole('link', { name: 'Connections', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Connections' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Run connection check' })).toBeEnabled()
  await page.getByRole('button', { name: 'Run connection check' }).click()
  await expect(page.getByRole('status')).toContainText('GitHub connected as fixture-user.')
  const csrf = await context.request.post('/api/auth/logout', { data: {}, headers: { Origin: 'http://127.0.0.1:5173' } })
  expect(csrf.status()).toBe(403)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Connections' })).toBeVisible()
  await expect(page.getByText('Cached responses', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('cache-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await expect(page.getByRole('button', { name: 'Expand sidebar' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Preview cache' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('admin-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  await expect(page).toHaveURL(/\/login$/)
  expect((await context.request.get('/api/workspace/preview-cache')).status()).toBe(401)
})
