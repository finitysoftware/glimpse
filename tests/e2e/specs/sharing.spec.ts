test('a link copies saved file visibility and its visitor sees only the selected files and their history', async ({ page, browser }, testInfo) => {
  await page.getByRole('link', { name: /fixture\/alpha/ }).click()
  await page.getByRole('button', { name: 'File visibility' }).click()
  // Wait for the saved rules first; an earlier test may already have selected README.md on this branch.
  await expect(page.getByRole('checkbox', { name: 'Visible to visitors: file README.md' })).toBeEnabled()
  await page.getByRole('checkbox', { name: 'Visible to visitors: file README.md' }).setChecked(true)
  const save = page.getByRole('button', { name: 'Save visibility' })
  if (await save.isVisible()) {
    await save.click()
    await expect(page.getByText('Visibility saved. It applies to new links.')).toBeVisible()
  }
  await expect(page.getByRole('region', { name: 'File visibility' }).getByText(/^1 of \d+ files visible to visitors$/)).toBeVisible()
  await page.getByRole('button', { name: 'Access links', exact: true }).click()
  await page.getByLabel('Link name').fill('Selected files')
  const mainFiles = page.getByRole('radiogroup', { name: 'File visibility for main' })
  await expect(mainFiles.getByRole('radio', { name: 'Selected files' })).toBeChecked()
  await expect(mainFiles).toContainText('Visitors see 1 selected file')
  await expect(mainFiles.getByRole('list', { name: 'Selected files in main' })).toHaveText('README.md')
  await page.getByLabel('Allow history', { exact: true }).check()
  await expect(page.getByRole('list', { name: 'History by branch' })).toContainText('Only changes to the 1 selected file, including its earlier versions.')
  await expect(mainFiles.getByText('History: only these files')).toBeVisible()
  await page.getByRole('button', { name: 'Create link', exact: true }).click()
  const url = await page.getByLabel('Access URL').inputValue()
  await expect(page.getByText('main: 1 selected file', { exact: false })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('selected-link-admin.png'), fullPage: true })
  const context = await browser.newContext()
  try {
    const visitor = await context.newPage()
    await visitor.goto(url)
    await expect(visitor.getByRole('button', { name: /README\.md/ })).toBeVisible()
    await expect(visitor.getByRole('button', { name: /App\.xaml/ })).toHaveCount(0)
    await expect(visitor.getByRole('button', { name: /docs/ })).toHaveCount(0)
    // Filtered history: only commits that change README.md, neutral messages, and no hidden file in the diff list.
    await visitor.getByRole('button', { name: 'History', exact: true }).click()
    const commits = visitor.getByRole('complementary', { name: 'Commit history' })
    await expect(commits.getByText('Only changes to files shared through this link are listed.')).toBeVisible()
    await expect(commits.getByRole('button', { name: /Changes to shared files/ })).toHaveCount(4)
    await expect(visitor.getByRole('region', { name: 'Diff for README.md' })).toContainText('Old README')
    await expect(visitor.getByText(/Improve application startup|Merge startup improvements|Alex Doe/)).toHaveCount(0)
    await expect(visitor.getByRole('button', { name: /App\.xaml\.cs|logo\.png|čitaj me/ })).toHaveCount(0)
    await visitor.screenshot({ path: testInfo.outputPath('selected-link-history.png'), fullPage: true })
    await visitor.getByRole('button', { name: 'Files', exact: true }).click()
    const shareId = new URL(url).pathname.split('/').at(-1)
    const hidden = await visitor.request.get(`/api/shares/${shareId}/browse?kind=file&path=App.xaml`)
    const missing = await visitor.request.get(`/api/shares/${shareId}/browse?kind=file&path=missing.txt`)
    expect([hidden.status(), (await hidden.json()).error.code]).toEqual([missing.status(), (await missing.json()).error.code])
    await visitor.screenshot({ path: testInfo.outputPath('selected-link-visitor.png'), fullPage: true })
  } finally { await context.close() }
})
