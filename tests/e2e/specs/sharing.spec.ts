async function createLink(page: Page, name: string) {
  await page.getByRole('button', { name: 'Access links', exact: true }).click()
  await page.getByLabel('Link name').fill(name)
  await page.getByRole('radiogroup', { name: 'File visibility for main' }).getByRole('radio', { name: 'Entire branch' }).check()
  await page.getByLabel('Allow history', { exact: true }).check()
  await page.getByRole('button', { name: 'Create link', exact: true }).click()
  const url = page.getByLabel('Access URL')
  await expect(url).toHaveValue(/\/s\/[a-f0-9]{32}#[a-f0-9]{64}$/)
  return url.inputValue()
}

async function resizePane(page: Page, name: string) {
  const handle = page.getByRole('separator', { name })
  const width = Number(await handle.getAttribute('aria-valuenow'))
  const bounds = await handle.boundingBox()
  await page.mouse.move(bounds!.x + bounds!.width / 2, bounds!.y + 80)
  await page.mouse.down()
  await page.mouse.move(bounds!.x + 90, bounds!.y + 80, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => Number(await handle.getAttribute('aria-valuenow'))).toBeGreaterThan(width)
  await handle.focus()
  await page.keyboard.press('Home')
  await expect(handle).toHaveAttribute('aria-valuenow', '200')
  await page.keyboard.press('ArrowRight')
  await expect(handle).toHaveAttribute('aria-valuenow', '220')
}

