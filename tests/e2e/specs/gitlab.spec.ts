import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  test.skip(!process.env.GLIMPSE_TEST_DB_DSN, 'A dedicated MySQL/MariaDB database is required.')
  await page.goto('/app')
  await page.getByLabel('Username').fill('e2e.gitlab')
  await page.getByLabel('Password', { exact: true }).fill('local-e2e-gitlab-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Repositories', exact: true })).toBeVisible()
})

test('GitHub and GitLab repositories share one list with platform badges and a platform filter', async ({ page }, testInfo) => {
  const gitlabRepository = page.getByRole('link', { name: /group\/sub\/alpha/ })
  const githubRepository = page.getByRole('link', { name: /fixture\/alpha/ })
  await expect(gitlabRepository).toBeVisible()
  await expect(githubRepository).toBeVisible()
  await expect(gitlabRepository.getByText('GitLab', { exact: true })).toBeVisible()
  await expect(githubRepository.getByText('GitHub', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: /group\/beta/ }).getByText('Internal', { exact: true })).toBeVisible()
  await expect(page.getByText(/Available through your/)).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('platforms-desktop.png'), fullPage: true })

  const trigger = page.getByRole('button', { name: /All platforms/ })
  await trigger.click()
  const github = page.getByRole('menuitemcheckbox', { name: 'GitHub', exact: true })
  await expect(github).toHaveAttribute('aria-checked', 'true')
  await expect(page.getByRole('menuitemcheckbox', { name: 'GitLab', exact: true })).toHaveAttribute('aria-checked', 'true')
  await page.screenshot({ path: testInfo.outputPath('platform-filter-open.png') })
  await github.click()
  await expect(github).toHaveAttribute('aria-checked', 'false')
  await expect(githubRepository).toHaveCount(0)
  await expect(gitlabRepository).toBeVisible()
  expect(new URL(page.url()).searchParams.get('platforms')).toBe('gitlab')
  const gitlab = page.getByRole('menuitemcheckbox', { name: 'GitLab', exact: true })
  await expect(gitlab).toHaveAttribute('aria-disabled', 'true')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await page.reload()
  await expect(gitlabRepository).toBeVisible()
  await expect(githubRepository).toHaveCount(0)

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click()
  await page.getByRole('button', { name: /Platforms/ }).click()
  await page.getByRole('menuitemcheckbox', { name: 'GitHub', exact: true }).click()
  await expect(githubRepository).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('platforms-mobile.png'), fullPage: true })
})

test('a GitLab project is browsed and shared, and the visitor never sees the platform', async ({ page, browser }, testInfo) => {
  await page.getByRole('link', { name: /group\/sub\/alpha/ }).click()
  await expect(page).toHaveURL(/\/app\/gitlab\/42$/)
  await expect(page.getByText('GitLab · group/sub', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { level: 1, name: 'alpha' })).toBeVisible()
  await page.getByRole('button', { name: /README.md/ }).click()
  await expect(page.locator('pre')).toContainText('# Project 42')
  await page.screenshot({ path: testInfo.outputPath('gitlab-project.png'), fullPage: true })

  await page.getByRole('button', { name: 'Access links', exact: true }).click()
  await expect(page.getByText('The link opens this repository without a GitLab account.')).toBeVisible()
  await page.getByLabel('Link name').fill('GitLab review')
  await page.getByRole('radiogroup', { name: 'File visibility for main' }).getByRole('radio', { name: 'Entire branch' }).check()
  await page.getByRole('button', { name: 'Create link', exact: true }).click()
  const url = await page.getByLabel('Access URL').inputValue()
  expect(url).toMatch(/\/s\/[a-f0-9]{32}#[a-f0-9]{64}$/)

  const visitor = await browser.newContext()
  try {
    const shared = await visitor.newPage()
    const bodies: string[] = []
    shared.on('response', response => { if (response.url().includes('/api/shares/')) void response.text().then(body => bodies.push(body), () => undefined) })
    await shared.goto(url)
    await shared.getByRole('button', { name: /README.md/ }).click()
    await expect(shared.locator('pre')).toContainText('# Project 42')
    await expect.poll(() => bodies.length).toBeGreaterThan(1)
    expect(bodies.join('\n')).not.toMatch(/gitlab|github/i)
    expect(await shared.locator('body').innerText()).not.toMatch(/GitLab|GitHub/)
    await shared.screenshot({ path: testInfo.outputPath('gitlab-visitor.png'), fullPage: true })
  } finally { await visitor.close() }
})

test('GitLab connects with its own address and disconnects without touching GitHub', async ({ page }, testInfo) => {
  await page.getByRole('link', { name: 'Connections', exact: true }).click()
  const card = page.getByRole('region', { name: 'GitLab connection' })
  await expect(card).toContainText('https://gitlab.example')
  await expect(card).toContainText('fixture-gitlab')
  await card.getByRole('button', { name: 'Configure GitLab', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Configure GitLab' })
  await expect(dialog.getByLabel('GitLab URL')).toHaveValue('https://gitlab.example')
  await expect(dialog.getByRole('link', { name: /Create a token on GitLab/ })).toHaveAttribute('href', 'https://gitlab.example/-/user_settings/personal_access_tokens?name=Glimpse&scopes=read_api')
  await page.screenshot({ path: testInfo.outputPath('configure-gitlab.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()

  await card.getByRole('button', { name: 'Disconnect', exact: true }).click()
  const confirm = page.getByRole('alertdialog', { name: 'Disconnect GitLab?' })
  await confirm.getByRole('button', { name: 'Disconnect GitLab', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('GitLab disconnected.')
  await expect(card.getByRole('button', { name: 'Disconnect', exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'GitHub connection' }).getByRole('button', { name: 'Disconnect', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Repositories', exact: true }).click()
  await expect(page.getByText('Available through your GitHub connection')).toBeVisible()
  await expect(page.getByRole('link', { name: /group\/sub\/alpha/ })).toHaveCount(0)
  await expect(page.getByRole('link', { name: /fixture\/alpha/ })).toBeVisible()
})
